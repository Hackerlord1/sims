/**
 * Generates reference documentation from the code, so it cannot drift from what the system enforces:
 *
 *   docs/role-permission-matrix.md   — from src/lib/permissions.ts
 *   docs/entities.md                 — from the Prisma schema (DMMF)
 *   docs/openapi.json                — from the registered API routes
 *
 *   npm run docs
 */
import { writeFileSync } from "node:fs";
import path from "node:path";
import { Prisma } from "@prisma/client";
import { ACTION_LABELS, ACTIONS, ASSIGNMENT_REQUIRED_ROLES, MODULE_LABELS, MODULES, ROLE_CLEARANCE_CAP, ROLE_LABELS, ROLES, SENSITIVE_MODULE_OVERRIDES, roleAllows } from "@/lib/permissions";
import { enumLabel } from "@/lib/enums";

const docs = path.resolve(__dirname, "../docs");
const header = (source: string) => `<!-- Generated by \`npm run docs\` from ${source}. Do not edit by hand. -->\n\n`;

function matrix() {
  const code: Record<string, string> = {};
  for (const a of ACTIONS) code[a] = ACTION_LABELS[a];
  const lines = [
    header("src/lib/permissions.ts"),
    "# Role and permission matrix",
    "",
    "Permissions are enforced on the server for every request. The browser only uses them to hide controls.",
    "On top of the role grants below, every case-linked record is also filtered by:",
    "",
    "- **Company/branch scope** — the user's assigned companies and branches (unscoped roles see assigned cases only).",
    `- **Assignment** — ${[...ASSIGNMENT_REQUIRED_ROLES].map((r) => ROLE_LABELS[r]).join(", ")} see only cases they are assigned to.`,
    "- **Confidentiality clearance** — a user sees a record only if their clearance (capped by role) covers its level.",
    `- **Sensitive modules** — ${Object.entries(SENSITIVE_MODULE_OVERRIDES)
      .map(([m, roles]) => `${MODULE_LABELS[m as keyof typeof MODULE_LABELS]} (except ${[...roles!].map((r) => ROLE_LABELS[r]).join(", ")})`)
      .join("; ")} additionally require the user to be assigned to the case.`,
    "- **Restricted cases** — need-to-know: only assigned users (and the System Administrator) can open them.",
    "- **Maker-checker** — nobody can approve, verify or decide their own request.",
    "",
    "## Clearance cap per role",
    "",
    "| Role | Highest clearance |",
    "| --- | --- |",
    ...ROLES.map((r) => `| ${ROLE_LABELS[r]} | ${enumLabel(ROLE_CLEARANCE_CAP[r])} |`),
    "",
    "## Actions by module",
    "",
    "Legend: " + ACTIONS.map((a, i) => `**${String.fromCharCode(65 + i)}** ${ACTION_LABELS[a]}`).join(" · "),
    "",
  ];
  const letter = (a: (typeof ACTIONS)[number]) => String.fromCharCode(65 + ACTIONS.indexOf(a));
  lines.push(`| Module | ${ROLES.map((r) => ROLE_LABELS[r]).join(" | ")} |`);
  lines.push(`| --- | ${ROLES.map(() => "---").join(" | ")} |`);
  for (const m of MODULES) {
    lines.push(
      `| ${MODULE_LABELS[m]} | ${ROLES.map(
        (r) =>
          ACTIONS.filter((a) => roleAllows(r, m, a))
            .map(letter)
            .join("") || "—",
      ).join(" | ")} |`,
    );
  }
  lines.push("");
  writeFileSync(path.join(docs, "role-permission-matrix.md"), lines.join("\n"));
}

function entities() {
  const models = Prisma.dmmf.datamodel.models;
  const lines = [header("prisma/schema.prisma"), "# Entity summary", "", `${models.length} tables. Money columns are \`numeric(18,2)\`; identifiers are CUIDs.`, ""];
  lines.push("| Entity | Fields | Relations | Soft delete | Optimistic lock | Unique keys |", "| --- | ---: | --- | :---: | :---: | --- |");
  for (const m of models) {
    const scalars = m.fields.filter((f) => f.kind !== "object");
    const relations = [...new Set(m.fields.filter((f) => f.kind === "object").map((f) => f.type))];
    const uniques = [...m.fields.filter((f) => f.isUnique).map((f) => f.name), ...m.uniqueFields.map((u) => u.join("+"))];
    lines.push(
      `| ${m.name} | ${scalars.length} | ${relations.join(", ") || "—"} | ${m.fields.some((f) => f.name === "isDeleted") ? "✓" : ""} | ${m.fields.some((f) => f.name === "version") ? "✓" : ""} | ${uniques.join(", ") || "—"} |`,
    );
  }
  lines.push("", "## Enumerations", "");
  for (const e of Prisma.dmmf.datamodel.enums) lines.push(`- **${e.name}**: ${e.values.map((v) => v.name).join(", ")}`);
  lines.push("");
  writeFileSync(path.join(docs, "entities.md"), lines.join("\n"));
}

async function openapi() {
  const { apiRouter } = await import("@/server/api");
  const { buildOpenApi } = await import("@/server/api/openapi");
  writeFileSync(path.join(docs, "openapi.json"), JSON.stringify(buildOpenApi(apiRouter), null, 2) + "\n");
}

async function main() {
  matrix();
  entities();
  await openapi();
  console.log("Wrote docs/role-permission-matrix.md, docs/entities.md and docs/openapi.json.");
  process.exit(0);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
