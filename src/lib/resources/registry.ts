// Declarative definitions of every case record type. One definition drives validation, the REST
// API, tables, forms, bulk-import templates and column mapping. Shared by browser and server.
import type { EnumName } from "@/lib/enums";
import type { FieldDef, ResourceDef } from "@/lib/resources/types";

type Opts = Partial<Omit<FieldDef, "name" | "label" | "type">>;

const text = (name: string, label: string, o: Opts = {}): FieldDef => ({ name, label, type: "text", max: 300, ...o });
const area = (name: string, label: string, o: Opts = {}): FieldDef => ({ name, label, type: "textarea", max: 20000, ...o });
const money = (name: string, label: string, o: Opts = {}): FieldDef => ({ name, label, type: "money", sortable: true, ...o });
const date = (name: string, label: string, o: Opts = {}): FieldDef => ({ name, label, type: "date", sortable: true, ...o });
const dateTime = (name: string, label: string, o: Opts = {}): FieldDef => ({ name, label, type: "datetime", sortable: true, ...o });
const en = (name: string, label: string, e: EnumName, o: Opts = {}): FieldDef => ({
  name,
  label,
  type: "enum",
  enum: e,
  filterable: true,
  sortable: true,
  ...o,
});
const bool = (name: string, label: string, o: Opts = {}): FieldDef => ({ name, label, type: "boolean", ...o });
const user = (name: string, label: string, o: Opts = {}): FieldDef => ({ name, label, type: "user", filterable: true, ...o });
const rel = (name: string, label: string, relation: string, o: Opts = {}): FieldDef => ({
  name,
  label,
  type: "relation",
  relation,
  ...o,
});
const computed = (name: string, label: string, o: Opts = {}): FieldDef => ({ name, label, type: "computed", readOnly: true, ...o });
const ref = (name = "reference"): FieldDef => ({
  name,
  label: "Reference",
  type: "text",
  readOnly: true,
  mono: true,
  list: true,
  sortable: true,
  searchable: true,
});
const subFile = (): FieldDef => rel("subFileId", "Sub-file", "subfiles", { filterable: true, importAliases: ["subfile", "sub file reference"] });

